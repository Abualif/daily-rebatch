import requests
from datetime import date
import calendar

# ================= CONFIG =================

BASE_URL = "http://batch2.pitjarus.co:2158/replicationManual"

ID_LIST = [1266, 1267, 1268, 1269, 1270, 1272, 981, 983, 982, 984, 1081]

# ID yang harus rebatch sampai akhir bulan
FULL_MONTH_IDS = [1265]

TIMEOUT = 600

# ================= DATE LOGIC =================

today = date.today()

start_date = today.replace(day=1)
end_today  = today

# hitung akhir bulan
last_day = calendar.monthrange(today.year, today.month)[1]
end_month = today.replace(day=last_day)

START_DATE = start_date.strftime("%Y-%m-%d")
END_TODAY  = end_today.strftime("%Y-%m-%d")
END_MONTH  = end_month.strftime("%Y-%m-%d")

print("Default Rebatch Range:")
print("FROM :", START_DATE)
print("TO   :", END_TODAY)

# ================= EXECUTE =================

for batch_id in ID_LIST:

    # cek apakah termasuk rebatch full month
    if batch_id in FULL_MONTH_IDS:
        end_date = END_MONTH
    else:
        end_date = END_TODAY

    url = f"{BASE_URL}/{batch_id}/{START_DATE}/{end_date}"

    print("\nCalling:", url)

    try:
        res = requests.get(url, timeout=TIMEOUT)

        if res.status_code == 200:
            print("✅ SUCCESS")
        else:
            print("❌ FAILED:", res.status_code)

    except Exception as e:
        print("❌ ERROR:", e)